package report

import (
	"fmt"
	"math"
	"time"

	"github.com/go-pdf/fpdf"

	"rearview/internal/store"
)

// Incident is everything a one-page report shows.
type Incident struct {
	Event    store.Event
	Segment  store.Segment
	Loc      *time.Location
	Frames   []Frame          // up to 3 key frames
	Track    []store.GPSPoint // the trip's GPS, for the graph
	ClipPath string
	Version  string
}

// Frame is a JPEG and its time in the file.
type Frame struct {
	Path     string
	TOffsetS float64
}

// GraphPoint is one sample for the speed and acceleration graph.
type GraphPoint struct {
	T        float64 // seconds relative to the event
	SpeedKmh float64
	AccelG   float64 // longitudinal, from the GPS speed: negative = braking
}

// Graph derives speed and longitudinal acceleration (Δv/Δt in g) for the
// window seconds around at. The camera stores no accelerometer data, so G is
// computed from the 1 Hz GPS speed.
func Graph(track []store.GPSPoint, at time.Time, window float64) []GraphPoint {
	var out []GraphPoint
	var prev *store.GPSPoint
	for i := range track {
		p := &track[i]
		rel := p.TS.Sub(at).Seconds()
		if rel < -window-1 || rel > window {
			prev = p
			continue
		}
		g := 0.0
		if prev != nil {
			if dt := p.TS.Sub(prev.TS).Seconds(); dt > 0 && dt <= 2 {
				g = (p.SpeedKmh - prev.SpeedKmh) / 3.6 / dt / 9.81
			}
		}
		prev = p
		if rel >= -window {
			out = append(out, GraphPoint{rel, p.SpeedKmh, g})
		}
	}
	return out
}

// WritePDF lays out the incident on one A4 page, readable in black and white.
func WritePDF(path string, in Incident) error {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(15, 15, 15)
	pdf.SetAutoPageBreak(false, 10)
	pdf.AddPage()
	e := in.Event
	local := e.TS.In(in.Loc)

	pdf.SetFont("Helvetica", "B", 18)
	pdf.CellFormat(0, 10, fmt.Sprintf("Incident report: %s", title(e.Type)), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 10)
	pdf.CellFormat(0, 5, fmt.Sprintf("Event %d, %s (%s UTC)", e.ID, local.Format("Monday 2 January 2006, 15:04:05 MST"), e.TS.UTC().Format("15:04:05")), "", 1, "L", false, 0, "")
	pdf.Ln(2)

	rows := [][2]string{
		{"Type", title(e.Type) + " (" + e.Source + ")"},
		{"Score", fmt.Sprintf("%.2f (0 to 1, higher is more severe)", e.Score)},
		{"Camera", fallback(e.Camera, "vehicle motion (GPS)")},
		{"Location", position(e)},
		{"Trip", fmt.Sprintf("%d", e.TripID)},
		{"Recording", fmt.Sprintf("%s at %.1f s", in.Segment.SourceName, e.TS.Sub(in.Segment.StartedAt).Seconds())},
		{"Details", e.Details},
		{"Clip", fallback(in.ClipPath, "-")},
	}
	for _, r := range rows {
		pdf.SetFont("Helvetica", "B", 10)
		pdf.CellFormat(28, 6, r[0], "", 0, "L", false, 0, "")
		pdf.SetFont("Helvetica", "", 10)
		pdf.MultiCell(0, 6, r[1], "", "L", false)
	}
	pdf.Ln(3)

	// Key frames, side by side.
	if n := len(in.Frames); n > 0 {
		const gap = 3.0
		w := (180 - gap*float64(n-1)) / float64(n)
		h := w * 9 / 16
		y := pdf.GetY()
		for i, f := range in.Frames {
			x := 15 + float64(i)*(w+gap)
			pdf.ImageOptions(f.Path, x, y, w, h, false, fpdf.ImageOptions{ImageType: "JPG"}, 0, "")
			pdf.Rect(x, y, w, h, "D")
			pdf.SetXY(x, y+h+1)
			pdf.SetFont("Helvetica", "", 8)
			rel := f.TOffsetS - e.TS.Sub(in.Segment.StartedAt).Seconds()
			pdf.CellFormat(w, 4, fmt.Sprintf("%+.1f s", rel), "", 0, "C", false, 0, "")
		}
		pdf.SetY(y + h + 8)
	}

	drawGraph(pdf, Graph(in.Track, e.TS, 15), pdf.GetY()+2)

	pdf.SetY(282)
	pdf.SetFont("Helvetica", "I", 8)
	pdf.CellFormat(0, 4, fmt.Sprintf("Generated by rearview %s on %s. Speed from GPS (1 Hz); acceleration derived from the speed.",
		in.Version, time.Now().In(in.Loc).Format("2006-01-02 15:04")), "", 0, "L", false, 0, "")
	return pdf.OutputFileAndClose(path)
}

func drawGraph(pdf *fpdf.Fpdf, pts []GraphPoint, top float64) {
	const left, width, height = 30.0, 160.0, 70.0
	pdf.SetFont("Helvetica", "B", 11)
	pdf.SetXY(15, top)
	pdf.CellFormat(0, 6, "Speed and longitudinal G, 15 s either side", "", 1, "L", false, 0, "")
	y0 := top + 8
	pdf.SetLineWidth(0.2)
	pdf.SetDrawColor(0, 0, 0)
	pdf.Rect(left, y0, width, height, "D")
	if len(pts) == 0 {
		pdf.SetXY(left, y0+height/2)
		pdf.CellFormat(width, 5, "no GPS data around this moment", "", 0, "C", false, 0, "")
		return
	}
	maxV := 10.0
	maxG := 0.3
	for _, p := range pts {
		maxV = math.Max(maxV, p.SpeedKmh)
		maxG = math.Max(maxG, math.Abs(p.AccelG))
	}
	maxV = math.Ceil(maxV/20) * 20
	maxG = math.Ceil(maxG*10) / 10
	xOf := func(t float64) float64 { return left + (t+15)/30*width }
	yV := func(v float64) float64 { return y0 + height - v/maxV*height }
	yG := func(g float64) float64 { return y0 + height/2 - g/maxG*height/2 }

	// Grid and labels.
	pdf.SetFont("Helvetica", "", 7)
	pdf.SetDrawColor(180, 180, 180)
	for i := 0; i <= 4; i++ {
		y := y0 + height*float64(i)/4
		pdf.Line(left, y, left+width, y)
		pdf.SetXY(left-14, y-2)
		pdf.CellFormat(12, 4, fmt.Sprintf("%.0f", maxV*(1-float64(i)/4)), "", 0, "R", false, 0, "")
		pdf.SetXY(left+width+1, y-2)
		pdf.CellFormat(14, 4, fmt.Sprintf("%+.2f", maxG*(1-float64(i)/2)), "", 0, "L", false, 0, "")
	}
	for s := -15; s <= 15; s += 5 {
		pdf.SetXY(xOf(float64(s))-5, y0+height+1)
		pdf.CellFormat(10, 4, fmt.Sprintf("%+d s", s), "", 0, "C", false, 0, "")
	}
	pdf.SetXY(left-15, y0-5)
	pdf.CellFormat(20, 4, "km/h", "", 0, "L", false, 0, "")
	pdf.SetXY(left+width-2, y0-5)
	pdf.CellFormat(20, 4, "g", "", 0, "R", false, 0, "")

	// Event moment.
	pdf.SetDrawColor(0, 0, 0)
	pdf.SetDashPattern([]float64{0.6, 0.8}, 0)
	pdf.Line(xOf(0), y0, xOf(0), y0+height)
	pdf.SetDashPattern([]float64{}, 0)

	// Speed: solid, thick.
	pdf.SetLineWidth(0.6)
	for i := 1; i < len(pts); i++ {
		pdf.Line(xOf(pts[i-1].T), yV(pts[i-1].SpeedKmh), xOf(pts[i].T), yV(pts[i].SpeedKmh))
	}
	// G: dashed, thin.
	pdf.SetLineWidth(0.3)
	pdf.SetDashPattern([]float64{1.5, 1}, 0)
	for i := 1; i < len(pts); i++ {
		pdf.Line(xOf(pts[i-1].T), yG(pts[i-1].AccelG), xOf(pts[i].T), yG(pts[i].AccelG))
	}
	pdf.SetDashPattern([]float64{}, 0)

	// Legend.
	ly := y0 + height + 8
	pdf.SetLineWidth(0.6)
	pdf.Line(left, ly, left+10, ly)
	pdf.SetXY(left+12, ly-2)
	pdf.CellFormat(30, 4, "speed (km/h, left axis)", "", 0, "L", false, 0, "")
	pdf.SetLineWidth(0.3)
	pdf.SetDashPattern([]float64{1.5, 1}, 0)
	pdf.Line(left+70, ly, left+80, ly)
	pdf.SetDashPattern([]float64{}, 0)
	pdf.SetXY(left+82, ly-2)
	pdf.CellFormat(50, 4, "longitudinal G (right axis, negative = braking)", "", 0, "L", false, 0, "")
}

func title(t string) string {
	switch t {
	case "hard_brake":
		return "Hard braking"
	case "swerve":
		return "Swerve"
	case "g_spike":
		return "G-force spike"
	case "near_miss":
		return "Near-miss"
	case "following_close":
		return "Following too close"
	case "tailgated":
		return "Tailgated"
	}
	return t
}

func position(e store.Event) string {
	if !e.HasPos {
		return "unknown"
	}
	ns, ew := "N", "E"
	if e.Lat < 0 {
		ns = "S"
	}
	if e.Lon < 0 {
		ew = "W"
	}
	return fmt.Sprintf("%.5f %s, %.5f %s", math.Abs(e.Lat), ns, math.Abs(e.Lon), ew)
}

func fallback(s, d string) string {
	if s == "" {
		return d
	}
	return s
}
